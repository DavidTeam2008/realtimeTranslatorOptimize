#!/bin/bash
# Regenerate Duiyi/Order/App.order from a Release binary's symbol table,
# ordered by the actual startup call graph (see docs/13-startup-optimization.md).
#
# Why not hand-write mangled Swift symbols? They change on every wholemodule
# build (generic specialization, inlining). Generating from `nm` keeps the file
# exact and refreshable per release.
#
# Usage:
#   1) Archive or build Release:
#        xcodebuild -project Duiyi.xcodeproj -scheme Duiyi -configuration Release \
#          -sdk iphoneos -derivedDataPath build/Release -destination 'generic/platform=iOS' build
#   2) ./tools/generate-order-file.sh build/Release/Build/Products/Release-iphoneos/Duiyi.app/Duiyi
#   3) Commit Order/App.order
#
# For day-to-day Debug builds ORDER_FILE is intentionally empty (see project.pbxproj:
# only Release sets ORDER_FILE) so incremental builds stay fast.
set -euo pipefail

BINARY="${1:-}"
if [[ -z "$BINARY" ]]; then
  echo "usage: $0 <path-to-Release-Duiyi-binary>" >&2
  exit 1
fi
if [[ ! -f "$BINARY" ]]; then
  echo "binary not found: $BINARY" >&2
  exit 1
fi

OUT="Order/App.order"
mkdir -p "$(dirname "$OUT")"

# All __TEXT,__text symbols (must include static Swift symbols: no -g flag).
# `nm -nm` prints "<addr> (<seg>,<sect>) <type> <name>"; keep only text symbols.
SYMBOLS=$(xcrun nm -nm "$BINARY" | awk '$2 == "(__TEXT,__text)" {print $NF}' | sort -u)

# Startup execution order (first frame): earliest first.
# Each entry is a substring matched against mangled names; order within a group
# follows link order (stable). Keep this list in sync with DuiyiApp.init ->
# AppEnvironment -> RootView -> HomeView.
PATTERNS=(
  # C entry + Swift runtime main
  '^_main$'
  'DuiyiApp'
  'AppLaunchTracker'
  'AppEnvironment'
  'PreferencesStore'
  'AppLanguage.*inferredFromSystem'
  'DeferredTaskStore'
  'SwiftDataTaskStore'
  'InMemoryTaskStore'
  'TaskEntity'
  'TranscriptEntity'
  'DuiyiLog'
  'AppCoordinator'
  'AppRoute'
  'FeatureRegistry'
  'FeatureID'
  'RootView'
  'HomeView'
  'HomeModuleCard'
  'Tokens'
  'Copy'
  'HistoryViewModel'
  'HistoryRow'
  'OnboardingViewModel'
  'PermissionService'
  'SpeechAssetPreparer'
  'TranslationAvailabilityService'
  'BilingualSpeechEngine'
  'AudioEngineCapturer'
  'AudioSessionPolicy'
  'SystemSpeechSynthesizer'
  'FoundationModelsSummarizer'
  'TranscriptExportService'
  'StaticLanguageCatalog'
  'TaskSessionController'
  'TaskSession'
  'TaskTitle'
)

TMP=$(mktemp)
trap 'rm -f "$TMP" "$TMP.rest"' EXIT

{
  echo "# Auto-generated by tools/generate-order-file.sh"
  echo "# Source binary: $BINARY"
  echo "# Date: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# ld -order_file format: one mangled symbol per line, earliest first."
} > "$TMP"

REST=$(mktemp)
echo "$SYMBOLS" > "$REST"

for pat in "${PATTERNS[@]}"; do
  # Exact _main first, rest substring match on mangled Swift names.
  if [[ "$pat" == "^_main\$" ]]; then
    grep -x '_main' "$REST" >> "$TMP" || true
  else
    grep -E "$pat" "$REST" >> "$TMP" || true
  fi
  # Remove emitted lines so each symbol appears once (first matching group wins).
  grep -Ev "$pat" "$REST" > "$REST.tmp" || true
  mv "$REST.tmp" "$REST"
done

# Deduplicate while preserving order (nm -u already unique, but groups may overlap).
awk '!seen[$0]++' "$TMP" > "$OUT"

echo "Wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
echo "Verify with: xcodebuild ... build && otool -l <binary> | grep -A3 order"
